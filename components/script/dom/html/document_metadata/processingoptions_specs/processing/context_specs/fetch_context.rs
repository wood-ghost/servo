//! Servo-specific buffering/notification adapters around the standard callbacks.
//! These methods are not separately named WHATWG algorithms; do not invent step
//! numbers for them. The normative completion callbacks are in algorithms/callbacks.

use vstd::prelude::*;
use super::super::model::*;
use super::super::types::ServoUrlView;

verus! {

pub(crate) open spec fn process_request_body_ensures(
    before: LinkFetchContextView, after: LinkFetchContextView,
) -> bool { after == before }

pub(crate) open spec fn process_response_ensures(
    before: LinkFetchContextView, after: LinkFetchContextView,
) -> bool {
    // Servo currently discards fetch_metadata without updating this context.
    after == before
}

pub(crate) open spec fn process_response_chunk_ensures(
    before: LinkFetchContextView,
    chunk: Seq<u8>,
    after: LinkFetchContextView,
) -> bool {
    // Buffering supplies the byte sequence used by preload step 11.1.
    &&& after.kind == before.kind
    &&& after.url == before.url
    &&& after.link == before.link
    &&& after.response_body == if before.kind == LinkFetchContextTypeView::Preload {
        before.response_body + chunk
    } else { before.response_body }
    &&& after.capacity >= after.response_body.len()
}

pub(crate) open spec fn process_content_length_ensures(
    before: LinkFetchContextView,
    size: nat,
    after: LinkFetchContextView,
) -> bool {
    // BytesMut::reserve changes allocation capacity, not the accumulated bytes.
    &&& after == LinkFetchContextView { capacity: after.capacity, ..before }
    &&& after.capacity >= before.capacity
    &&& after.capacity >= before.response_body.len() + size
}

pub(crate) open spec fn link_fetch_context_type_into_initiator(
    kind: LinkFetchContextTypeView,
) -> Seq<char> {
    // The string in InitiatorType::LocalName, generated by IntoStaticStr(lowercase).
    match kind {
        LinkFetchContextTypeView::Prefetch => "prefetch"@,
        LinkFetchContextTypeView::Preload => "preload"@,
    }
}

pub(crate) open spec fn resource_timing_information(
    context: LinkFetchContextView,
) -> (Seq<char>, ServoUrlView) {
    (link_fetch_context_type_into_initiator(context.kind), context.url)
}

pub(crate) open spec fn process_response_eof_effects(
    context: LinkFetchContextView,
    global: int,
    timing: int,
    failed: bool,
) -> Seq<CallbackEffect> {
    // Native submit_timing delegates to the resource-timing model.
    let effects = seq![CallbackEffect::SubmitTiming { global, timing, failed }];
    // The link-element response callback fires error/load, as specified by the
    // preload fetch-and-process callback (6.1) and the prefetch callback.
    match context.link {
        Some(element) => effects.push(CallbackEffect::FireEvent {
            element, name: if failed { "error"@ } else { "load"@ },
        }),
        None => effects,
    }
}

pub(crate) open spec fn process_csp_violations_effects(
    global: int,
    violations: Seq<int>,
) -> Seq<CallbackEffect> {
    // The actual report algorithm belongs to CSP, not HTML link processing.
    seq![CallbackEffect::ReportCspViolations { global, violations }]
}

pub(crate) open spec fn resource_timing_information_ensures(
    context: LinkFetchContextView,
    result: (Seq<char>, ServoUrlView),
) -> bool { result == resource_timing_information(context) }

} // verus!
